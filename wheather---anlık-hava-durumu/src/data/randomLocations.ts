export function getRandomLocation(excludeName?: string): CuratedLocation {
  const filtered = excludeName
    ? RANDOM_LOCATIONS.filter((l) => l.name !== excludeName)
    : RANDOM_LOCATIONS;
  const index = Math.floor(Math.random() * filtered.length);
  return filtered[index];
}
